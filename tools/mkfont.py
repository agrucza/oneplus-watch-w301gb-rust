#!/usr/bin/env python3
"""Turn TrueType fonts and a few drawings into the bitmaps the firmware
draws from: one byte per pixel saying how much of the pixel is covered
(0 to 255), which the chip's blitter blends into the picture in any colour.

Writes src/services/font_data.rs and the files in src/services/fonts/. Run
it again after changing anything below; the output is checked in, so the
build itself needs neither Python nor the font files.

The fonts of the Nightwatch design (Orbitron, Rajdhani, JetBrains Mono, all
under the Open Font License) are not in the repository. Fetch them once
from https://github.com/google/fonts (ofl/orbitron, ofl/rajdhani,
ofl/jetbrainsmono) into ~/.local/share/fonts/nightwatch, or point
NIGHTWATCH_FONTS at the folder that holds them.

usage: tools/mkfont.py
"""
import math
import os

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_RS = os.path.join(HERE, "..", "src", "services", "font_data.rs")
OUT_DIR = os.path.join(HERE, "..", "src", "services", "fonts")
NW = os.environ.get("NIGHTWATCH_FONTS", os.path.expanduser("~/.local/share/fonts/nightwatch"))

DEJAVU = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
ORBITRON = os.path.join(NW, "orbitron-Orbitron[wght].ttf")
RAJDHANI = os.path.join(NW, "rajdhani-Rajdhani-Bold.ttf")
JETBRAINS = os.path.join(NW, "jetbrainsmono-JetBrainsMono[wght].ttf")

rs = [
    "//! Character bitmaps and drawings for `services::font`. Generated by",
    "//! tools/mkfont.py; do not edit.",
    "",
    "use super::font::{Art, Font};",
    "",
]


def load(path, size, weight=None):
    font = ImageFont.truetype(path, size)
    if weight:
        font.set_variation_by_name(weight)
    return font


def save(name, data):
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, name + ".bin"), "wb") as f:
        f.write(bytes(data))
    return 'include_bytes!("fonts/%s.bin")' % name


def text_font(name, path, size, weight=None, tracking=0.0, proportional=False, doc="", last=126):
    """Characters 32 to `last` in cells of one size (95 ends at the
    underscore: capitals, digits and punctuation, no small letters). A
    proportional font also gets each character's advance; `tracking` (in
    em) is added to it."""
    font = load(path, size, weight)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    extra = round(tracking * size)
    advances = [round(font.getlength(chr(c))) + extra for c in range(32, last + 1)]
    width = max(advances) if proportional else round(font.getlength("M"))
    data = bytearray()
    for code in range(32, last + 1):
        cell = Image.new("L", (width, height), 0)
        ImageDraw.Draw(cell).text((0, 0), chr(code), font=font, fill=255)
        data += cell.tobytes()
    lower = name.lower()
    coverage = save(lower, data)
    advance = "&[]"
    if proportional:
        advance = "&[" + ", ".join(str(a) for a in advances) + "]"
    rs.append("/// %s: every character in a cell of %d x %d.%s" % (doc or os.path.basename(path), width, height, " Each has its own advance." if proportional else ""))
    rs.append("pub static %s: Font = Font { width: %d, height: %d, first: 32, count: %d, coverage: %s, advance: %s };" % (name, width, height, last - 31, coverage, advance))
    rs.append("")
    print("%-14s %3d x %3d  %7d bytes" % (name, width, height, len(data)))


def hero(name, size, glow_pad, glows):
    """The digits 0 to 9 of the big numerals, cut to the height the digits
    really have and all in cells of one width, and the same digits blurred
    into a glow, in larger cells that reach `glow_pad` pixels beyond the
    digit on every side. `glows` is a list of (blur radius, strength), as
    the design's text shadows."""
    font = load(ORBITRON, size, "Black")
    boxes = [font.getbbox(str(d)) for d in range(10)]
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    width = max(round(font.getlength(str(d))) for d in range(10))
    height = bottom - top
    digits, glow = bytearray(), bytearray()
    gw, gh = width + 2 * glow_pad, height + 2 * glow_pad
    for d in range(10):
        cell = Image.new("L", (width, height), 0)
        # Centred in its cell, so that the digits stand still as they change.
        x = (width - round(font.getlength(str(d)))) // 2
        ImageDraw.Draw(cell).text((x, -top), str(d), font=font, fill=255)
        digits += cell.tobytes()
        wide = Image.new("L", (gw, gh), 0)
        wide.paste(cell, (glow_pad, glow_pad))
        total = Image.new("L", (gw, gh), 0)
        for radius, strength in glows:
            layer = wide.filter(ImageFilter.GaussianBlur(radius / 2)).point(lambda v, s=strength: min(255, int(v * s)))
            total = ImageChops.add(total, layer)
        glow += total.tobytes()
    lower = name.lower()
    rs.append("/// Orbitron Black at %d pixels, the digits 0 to 9 only, each %d x %d." % (size, width, height))
    rs.append("pub static %s: Font = Font { width: %d, height: %d, first: 48, count: 10, coverage: %s, advance: &[] };" % (name, width, height, save(lower, digits)))
    rs.append("/// The same digits as a glow: cells of %d x %d, reaching %d pixels beyond the digit on every side." % (gw, gh, glow_pad))
    rs.append("pub static %s_GLOW: Font = Font { width: %d, height: %d, first: 48, count: 10, coverage: %s, advance: &[] };" % (name, gw, gh, save(lower + "_glow", glow)))
    rs.append("pub const %s_GLOW_PAD: i32 = %d;" % (name, glow_pad))
    rs.append("")
    print("%-14s %3d x %3d  %7d bytes, glow %d x %d  %d bytes" % (name, width, height, len(digits), gw, gh, len(glow)))


def numerals(name, size, weight, doc):
    """The digits 0 to 9 and the colon of the display font, cut to the
    height the digits really have, each centred in a cell as wide as the
    widest digit."""
    font = load(ORBITRON, size, weight)
    chars = "0123456789:"
    boxes = [font.getbbox(c) for c in chars]
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    width = max(round(font.getlength(c)) for c in chars)
    height = bottom - top
    data = bytearray()
    for c in chars:
        cell = Image.new("L", (width, height), 0)
        ImageDraw.Draw(cell).text(((width - round(font.getlength(c))) // 2, -top), c, font=font, fill=255)
        data += cell.tobytes()
    rs.append("/// %s: the digits and the colon, each %d x %d." % (doc, width, height))
    rs.append("pub static %s: Font = Font { width: %d, height: %d, first: 48, count: 11, coverage: %s, advance: &[] };" % (name, width, height, save(name.lower(), data)))
    rs.append("")
    print("%-14s %3d x %3d  %7d bytes" % (name, width, height, len(data)))


def art(name, image, doc):
    """A drawing of any size."""
    rs.append("/// %s (%d x %d)." % (doc, image.width, image.height))
    rs.append("pub static %s: Art = Art { width: %d, height: %d, coverage: %s };" % (name, image.width, image.height, save(name.lower(), image.tobytes())))
    print("%-14s %3d x %3d  %7d bytes" % (name, image.width, image.height, image.width * image.height))


def path_points(d):
    """The corners of an SVG path made of the commands M, L, H, V, A and
    Z (all the design's icons used here need), with arcs turned into
    short straight pieces. Returns a list of closed or open outlines."""
    import re
    tokens = re.findall(r"[MLHVAZ]|-?\d*\.?\d+", d)
    outlines, current, i, x, y = [], [], 0, 0.0, 0.0
    def number():
        nonlocal i
        i += 1
        return float(tokens[i - 1])
    command = None
    while i < len(tokens):
        if tokens[i] in "MLHVAZ":
            command = tokens[i]
            i += 1
        if command == "M":
            if current:
                outlines.append(current)
            x, y = number(), number()
            current = [(x, y)]
            command = "L"
        elif command == "L":
            x, y = number(), number()
            current.append((x, y))
        elif command == "H":
            x = number()
            current.append((x, y))
        elif command == "V":
            y = number()
            current.append((x, y))
        elif command == "A":
            rx, ry, _turn, large, sweep, x2, y2 = (number() for _ in range(7))
            # From the two ends to the centre (SVG implementation notes,
            # F.6.5), for a circle; too small a radius grows to fit.
            dx, dy = (x - x2) / 2, (y - y2) / 2
            r = max(rx, math.hypot(dx, dy))
            k = math.sqrt(max(0.0, r * r - dx * dx - dy * dy)) / max(1e-9, math.hypot(dx, dy))
            if large == sweep:
                k = -k
            cx, cy = (x + x2) / 2 + k * dy, (y + y2) / 2 - k * dx
            a1, a2 = math.atan2(y - cy, x - cx), math.atan2(y2 - cy, x2 - cx)
            if sweep and a2 < a1:
                a2 += 2 * math.pi
            if not sweep and a2 > a1:
                a2 -= 2 * math.pi
            for step in range(1, 25):
                a = a1 + (a2 - a1) * step / 24
                current.append((cx + r * math.cos(a), cy + r * math.sin(a)))
            x, y = x2, y2
        elif command == "Z":
            current.append(current[0])
    if current:
        outlines.append(current)
    return outlines


def icon(name, size, d, doc, filled=False):
    """One of the design's icons (paths drawn on a 24 x 24 grid with a
    line width of 1.5, or filled shapes) at `size` pixels."""
    scale = 16
    big = Image.new("L", (size * scale, size * scale), 0)
    draw = ImageDraw.Draw(big)
    unit = size * scale / 24
    for outline in path_points(d):
        points = [(px * unit, py * unit) for px, py in outline]
        if filled:
            draw.polygon(points, fill=255)
        else:
            draw.line(points, fill=255, width=round(1.5 * unit), joint="curve")
    art(name, big.resize((size, size), Image.LANCZOS), doc)
    rs.append("")


def rim_text(name, text, size, radius, centre_angle, inward, doc):
    """A line of text bent along a circle of `radius` around the middle of
    the 454 x 454 face, centred on `centre_angle` (degrees clockwise from
    twelve o'clock). With `inward` the letters' tops point at the middle
    (for the lower half, so that it reads from left to right). The
    drawing is cut to what it covers; its place on the face is given as
    two constants."""
    scale, face = 4, 454
    font = load(JETBRAINS, size * scale, "Medium")
    spacing = 2.5 * scale
    advances = [font.getlength(ch) + spacing for ch in text]
    total = sum(advances) - spacing
    r = radius * scale
    canvas = Image.new("L", (face * scale, face * scale), 0)
    ascent, descent = font.getmetrics()
    along = -total / 2
    for ch, advance in zip(text, advances):
        mid = along + (advance - spacing) / 2
        # The angle of this letter's middle, and the letter drawn upright
        # with its baseline's middle at the centre of a square.
        angle = centre_angle + math.degrees(mid / r) * (-1 if inward else 1)
        side = int((ascent + descent) * 2)
        letter = Image.new("L", (side, side), 0)
        ImageDraw.Draw(letter).text((side / 2 - font.getlength(ch) / 2, side / 2 - ascent), ch, font=font, fill=255)
        turned = letter.rotate(-(angle + (180 if inward else 0)), resample=Image.BICUBIC)
        t = math.radians(angle - 90)
        x, y = face * scale / 2 + r * math.cos(t), face * scale / 2 + r * math.sin(t)
        canvas.paste(Image.composite(turned, canvas.crop((int(x - side / 2), int(y - side / 2), int(x - side / 2) + side, int(y - side / 2) + side)), turned), (int(x - side / 2), int(y - side / 2)))
        along += advance
    small = canvas.resize((face, face), Image.LANCZOS)
    box = small.getbbox()
    art(name, small.crop(box), doc)
    rs.append("pub const %s_AT: (i32, i32) = (%d, %d);" % (name, box[0], box[1]))
    rs.append("")


