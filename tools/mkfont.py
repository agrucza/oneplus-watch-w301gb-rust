#!/usr/bin/env python3
"""Turn a monospaced TrueType font into the character bitmaps the firmware
draws text from: one byte per pixel saying how much of the pixel the
character covers (0 to 255), which the chip's blitter blends into the
picture.

Writes src/services/font_data.rs. Run it again after changing FONT or SIZES;
the output is checked in, so the build itself needs neither Python nor the
font file.

usage: tools/mkfont.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
# (name, size of the font in pixels)
SIZES = [("SMALL", 16), ("MEDIUM", 20), ("LARGE", 27)]
FIRST, LAST = 32, 126

out = [
    "//! Character bitmaps for `services::font`. Generated by tools/mkfont.py from",
    "//! %s; do not edit." % os.path.basename(FONT),
    "",
    "use super::font::Font;",
    "",
]
for name, size in SIZES:
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    width = round(font.getlength("M"))
    height = ascent + descent
    data = bytearray()
    for code in range(FIRST, LAST + 1):
        cell = Image.new("L", (width, height), 0)
        ImageDraw.Draw(cell).text((0, 0), chr(code), font=font, fill=255)
        data += cell.tobytes()
    out.append("/// %s at %d pixels: every character is %d x %d." % (os.path.basename(FONT), size, width, height))
    out.append("pub static %s: Font = Font { width: %d, height: %d, first: %d, count: %d, coverage: &%s_COVERAGE };" % (name, width, height, FIRST, LAST - FIRST + 1, name))
    out.append("static %s_COVERAGE: [u8; %d] = [" % (name, len(data)))
    for i in range(0, len(data), 32):
        out.append("    " + ", ".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("];")
    out.append("")
    print("%s: %d x %d, %d bytes" % (name, width, height, len(data)))
path = os.path.join(os.path.dirname(__file__), "..", "src", "services", "font_data.rs")
open(path, "w").write("\n".join(out))
